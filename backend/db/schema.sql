-- AI Caller full schema
-- Run: psql $DATABASE_URL -f schema.sql

CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- Users / accounts
CREATE TABLE users (
  id          UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  email       TEXT UNIQUE NOT NULL,
  password    TEXT,                    -- null for Google OAuth
  name        TEXT,
  google_id   TEXT UNIQUE,
  timezone    TEXT DEFAULT 'Asia/Kolkata',
  credits     INTEGER DEFAULT 5000,   -- in paise (₹50 free = 5000p)
  created_at  TIMESTAMPTZ DEFAULT NOW()
);

-- AI Employees (agents)
CREATE TABLE employees (
  id          UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  user_id     UUID REFERENCES users(id) ON DELETE CASCADE,
  name        TEXT NOT NULL,
  call_type   TEXT NOT NULL CHECK (call_type IN ('instant','bulk','inbound')),
  language    TEXT NOT NULL DEFAULT 'English',
  industry    TEXT,
  brief       TEXT NOT NULL,           -- user's original description
  system_prompt TEXT,                  -- generated by LLM
  voice_id    TEXT DEFAULT 'hi-IN-MadhurNeural',
  status      TEXT DEFAULT 'active' CHECK (status IN ('active','paused','draft')),
  created_at  TIMESTAMPTZ DEFAULT NOW()
);

-- Phone numbers
CREATE TABLE phone_numbers (
  id          UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  user_id     UUID REFERENCES users(id) ON DELETE CASCADE,
  employee_id UUID REFERENCES employees(id) ON DELETE SET NULL,
  number      TEXT UNIQUE NOT NULL,
  provider    TEXT DEFAULT 'twilio',
  provider_sid TEXT,
  direction   TEXT DEFAULT 'both' CHECK (direction IN ('inbound','outbound','both')),
  monthly_cost INTEGER DEFAULT 7500,  -- paise
  active      BOOLEAN DEFAULT true,
  created_at  TIMESTAMPTZ DEFAULT NOW()
);

-- Campaigns (bulk calling)
CREATE TABLE campaigns (
  id           UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  user_id      UUID REFERENCES users(id) ON DELETE CASCADE,
  employee_id  UUID REFERENCES employees(id) ON DELETE SET NULL,
  name         TEXT NOT NULL,
  status       TEXT DEFAULT 'pending' CHECK (status IN ('pending','running','paused','completed','failed')),
  total_leads  INTEGER DEFAULT 0,
  called       INTEGER DEFAULT 0,
  rate_per_min INTEGER DEFAULT 10,    -- concurrent calls
  created_at   TIMESTAMPTZ DEFAULT NOW(),
  started_at   TIMESTAMPTZ,
  completed_at TIMESTAMPTZ
);

-- Leads / contacts
CREATE TABLE leads (
  id            UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  user_id       UUID REFERENCES users(id) ON DELETE CASCADE,
  campaign_id   UUID REFERENCES campaigns(id) ON DELETE SET NULL,
  employee_id   UUID REFERENCES employees(id) ON DELETE SET NULL,
  name          TEXT,
  phone         TEXT NOT NULL,
  channel       TEXT DEFAULT 'bulk' CHECK (channel IN ('inbound','instant','bulk')),
  outcome       TEXT CHECK (outcome IN ('qualified','interested','callback','not_interested','no_response','no_answer','busy','failed','voicemail')),
  sentiment     TEXT CHECK (sentiment IN ('positive','neutral','negative')),
  captured_data JSONB DEFAULT '{}',   -- key facts the agent captured
  hot           BOOLEAN DEFAULT false,
  created_at    TIMESTAMPTZ DEFAULT NOW()
);

-- Calls / conversations
CREATE TABLE calls (
  id             UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  user_id        UUID REFERENCES users(id) ON DELETE CASCADE,
  lead_id        UUID REFERENCES leads(id) ON DELETE SET NULL,
  employee_id    UUID REFERENCES employees(id) ON DELETE SET NULL,
  campaign_id    UUID REFERENCES campaigns(id) ON DELETE SET NULL,
  direction      TEXT DEFAULT 'outbound' CHECK (direction IN ('inbound','outbound')),
  channel        TEXT DEFAULT 'bulk' CHECK (channel IN ('inbound','instant','bulk')),
  provider_sid   TEXT,                -- Twilio/Plivo call SID
  phone_from     TEXT,
  phone_to       TEXT,
  status         TEXT DEFAULT 'initiated' CHECK (status IN ('initiated','ringing','in_progress','completed','failed','no_answer','busy')),
  duration_sec   INTEGER DEFAULT 0,
  credits_used   INTEGER DEFAULT 0,   -- paise
  transcript     JSONB DEFAULT '[]',  -- array of {role, text, ts}
  summary        TEXT,
  outcome        TEXT,
  sentiment      TEXT,
  recording_url  TEXT,
  started_at     TIMESTAMPTZ DEFAULT NOW(),
  ended_at       TIMESTAMPTZ
);

-- Instant lead webhooks
CREATE TABLE webhooks (
  id          UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  user_id     UUID REFERENCES users(id) ON DELETE CASCADE,
  employee_id UUID REFERENCES employees(id) ON DELETE CASCADE,
  secret      TEXT NOT NULL DEFAULT uuid_generate_v4(),
  name        TEXT,
  active      BOOLEAN DEFAULT true,
  created_at  TIMESTAMPTZ DEFAULT NOW()
);

-- Credit top-ups / billing
CREATE TABLE transactions (
  id          UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  user_id     UUID REFERENCES users(id) ON DELETE CASCADE,
  type        TEXT CHECK (type IN ('topup','call_debit','refund','free_credit')),
  amount      INTEGER NOT NULL,        -- paise, positive = credit, negative = debit
  description TEXT,
  reference   TEXT,
  created_at  TIMESTAMPTZ DEFAULT NOW()
);

-- API keys for developers
CREATE TABLE api_keys (
  id         UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  user_id    UUID REFERENCES users(id) ON DELETE CASCADE,
  key_hash   TEXT NOT NULL,
  name       TEXT,
  last_used  TIMESTAMPTZ,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Performance tracking (daily rollup)
CREATE TABLE perf_daily (
  id           UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  user_id      UUID REFERENCES users(id) ON DELETE CASCADE,
  employee_id  UUID REFERENCES employees(id) ON DELETE CASCADE,
  date         DATE NOT NULL,
  total_calls  INTEGER DEFAULT 0,
  qualified    INTEGER DEFAULT 0,
  avg_duration NUMERIC DEFAULT 0,
  credits_used INTEGER DEFAULT 0,
  UNIQUE(employee_id, date)
);

-- Indexes
CREATE INDEX idx_calls_user ON calls(user_id);
CREATE INDEX idx_calls_employee ON calls(employee_id);
CREATE INDEX idx_leads_user ON leads(user_id);
CREATE INDEX idx_leads_campaign ON leads(campaign_id);
CREATE INDEX idx_campaigns_user ON campaigns(user_id);
